#!/usr/bin/env bash
# Validators of the live pipelining testbed, one per namespace made by wan-net.sh.
#
# Node i runs in st-n$i as the invoking user (sudo is only used to enter the namespace; setpriv
# drops back to the user before stellar-core starts). Data lives on the /ram tmpfs.
#
# Each node publishes to its own archive and reads the next node's, so it can catch up.
# Usage: wan-nodes.sh init <n> <close_ms> [accounts]
#                                  fresh configs and databases for n validators (genesis is
#                                  protocol 0 with a 100-op tx set limit; see upgrade)
#                                  ORG_SIZE=m groups consecutive validators into organizations of m
#                                  (quorum: 67% of organizations, 67% inside each)
#        wan-nodes.sh upgrade [max_tx_set_ops]
#                                  vote on every node for the current protocol and the limit
#        wan-nodes.sh set <KEY> <value>   set a config entry on every node (restart to apply)
#        wan-nodes.sh start | stop | status
#        wan-nodes.sh http <i> <command>   e.g. http 1 'info'
set -euo pipefail
BIN="${BIN:-$HOME/src/stellar-core-pipeline/src/stellar-core}"
W="${WAN_DIR:-/ram/wan}"
SEEDS="${SEEDS:-$HOME/src/lab-runs/wan/seeds.txt}"
ME_UID=$(id -u)
ME_GID=$(id -g)

nsrun() { # nsrun <i> <command...>: run a command in node i's namespace as this user
    local i="$1"
    shift
    sudo -n /usr/sbin/ip netns exec "st-n$i" setpriv --reuid="$ME_UID" --regid="$ME_GID" \
        --init-groups env HOME="$HOME" PATH="$PATH" "$@"
}

nodes() { ls -d "$W"/n* 2>/dev/null | sed 's|.*/n||' | sort -n; }

quorum_set() { # flat 67% of all validators, or with ORG_SIZE, 67% of organizations of ORG_SIZE
    echo "[QUORUM_SET]"
    echo "THRESHOLD_PERCENT=67"
    if [ -z "${ORG_SIZE:-}" ]; then
        echo "VALIDATORS=[$validators]"
        return
    fi
    head -n "$n" "$SEEDS" | awk -v s="$ORG_SIZE" '
        { o = int((NR - 1) / s) + 1; k[o] = k[o] (k[o] ? ", " : "") "\"" $2 "\"" }
        END { for (o = 1; o in k; o++)
                  printf "\n[QUORUM_SET.ORG%d]\nTHRESHOLD_PERCENT=67\nVALIDATORS=[%s]\n", o, k[o] }'
}

case "${1:-}" in
init)
    n="$2"
    close_ms="$3"
    accounts="${4:-20000}"
    mkdir -p "$(dirname "$SEEDS")"
    touch "$SEEDS"
    twins=(${WAN_WATCHERS:-})
    total=$((n + ${#twins[@]}))
    while [ "$(wc -l < "$SEEDS")" -lt "$total" ]; do
        "$BIN" gen-seed | awk '/Secret seed/ { s = $3 } /Public/ { print s, $2 }' >> "$SEEDS"
    done
    rm -rf "$W"
    validators=$(head -n "$n" "$SEEDS" | awk '{ printf "%s\"%s\"", (NR > 1 ? ", " : ""), $2 }')
    for i in $(seq 1 "$total"); do
        d="$W/n$i"
        validator=$([ "$i" -le "$n" ] && echo true || echo false)
        mkdir -p "$d/buckets"
        seed=$(sed -n "${i}p" "$SEEDS" | cut -d' ' -f1)
        peers=$(for j in $(seq 1 "$total"); do [ "$j" = "$i" ] || printf '"10.77.0.%s:11625",' "$j"; done)
        cat > "$d/stellar.cfg" <<EOF
# Live pipelining testbed, validator $i of $n (generated by wan-nodes.sh)
NETWORK_PASSPHRASE="Pipelining study WAN testbed"
NODE_SEED="$seed self"
NODE_IS_VALIDATOR=$validator
DATABASE="sqlite3://$d/stellar.db"
BUCKET_DIR_PATH="$d/buckets"
LOG_FILE_PATH="$d/node.log"
PEER_PORT=11625
HTTP_PORT=11626
PUBLIC_HTTP_PORT=false
KNOWN_PEERS=[${peers%,}]
PREFERRED_PEERS=[${peers%,}]
UNSAFE_QUORUM=true
RUN_STANDALONE=false
GENESIS_TEST_ACCOUNT_COUNT=$accounts
ARTIFICIALLY_GENERATE_LOAD_FOR_TESTING=true
ARTIFICIALLY_SET_CLOSE_TIME_FOR_TESTING=$close_ms

[HISTORY.local]
get="cp $W/n$(( i % n + 1 ))/history/{0} {1}"
put="cp {0} $d/history/{1}"
mkdir="mkdir -p $d/history/{0}"

$(quorum_set)
EOF
        # new-hist fails on the last validator (its "get" archive, n1, already exists); not needed here
        (cd "$d" && "$BIN" new-db --conf stellar.cfg > new-db.log 2>&1 &&
            { "$BIN" new-hist local --conf stellar.cfg >> new-db.log 2>&1 || true; })
    done
    echo "initialized $n validators and $((total - n)) watchers in $W (target close $close_ms ms, $accounts accounts)"
    ;;
start)
    for i in $(nodes); do
        d="$W/n$i"
        setsid nohup sudo -n /usr/sbin/ip netns exec "st-n$i" setpriv --reuid="$ME_UID" \
            --regid="$ME_GID" --init-groups env HOME="$HOME" PATH="$PATH" \
            bash -c "cd '$d' && echo \$\$ > pid && exec '$BIN' run --conf stellar.cfg" \
            > "$d/stdout.log" 2>&1 < /dev/null &
    done
    sleep 1
    bash "$0" status
    ;;
stop)
    for i in $(nodes); do
        f="$W/n$i/pid"
        [ -f "$f" ] && kill "$(cat "$f")" 2>/dev/null || true
    done
    sleep 2
    for i in $(nodes); do
        f="$W/n$i/pid"
        [ -f "$f" ] && kill -9 "$(cat "$f")" 2>/dev/null || true
        rm -f "$f"
    done
    ;;
status)
    for i in $(nodes); do
        f="$W/n$i/pid"
        if [ -f "$f" ] && kill -0 "$(cat "$f")" 2>/dev/null; then
            state=$(nsrun "$i" curl -s -m 2 "http://127.0.0.1:11626/info" |
                python3 -c 'import json, sys
i = json.load(sys.stdin)["info"]
print(i["state"], "ledger", i["ledger"]["num"], "peers", i["peers"]["authenticated_count"])' \
                2>/dev/null || echo "no answer")
            echo "n$i pid $(cat "$f"): $state"
        else
            echo "n$i: stopped"
        fi
    done
    ;;
upgrade)
    proto=$("$BIN" version 2>/dev/null | awk '!p && /ledger protocol version/ { print $NF; p = 1 }')
    proto="${UPGRADE_PROTOCOL:-$proto}"
    for i in $(nodes); do
        nsrun "$i" curl -s -m 10 "http://127.0.0.1:11626/upgrades?mode=set&upgradetime=$(date -u +%Y-%m-%dT%H:%M:%SZ)&protocolversion=$proto&maxtxsetsize=${2:-10000}"
        echo
    done
    ;;
set)
    for i in $(nodes); do
        f="$W/n$i/stellar.cfg"
        if grep -q "^$2=" "$f"; then
            sed -i "s|^$2=.*|$2=$3|" "$f"
        else
            sed -i "0,/^\[/s|^\[|$2=$3\n\n[|" "$f"
        fi
    done
    grep -h "^$2=" "$W"/n*/stellar.cfg | sort | uniq -c
    ;;
http)
    nsrun "$2" curl -s -m 10 "http://127.0.0.1:11626/$3"
    echo
    ;;
*)
    sed -n 2,17p "$0"
    exit 1
    ;;
esac
